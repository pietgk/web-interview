import {
  COVERAGE_METRICS as SHARED_COVERAGE_METRICS,
  createCombinedOwnedRuntimeReach,
  exactCoverage,
  normalizeCoveragePath,
  sumCoverage,
} from './coverage-producers.mjs'

/** @typedef {'statements' | 'branches' | 'functions' | 'lines'} CoverageMetric */
/** @typedef {{covered: number, total: number}} CoverageTuple */
/** @typedef {Record<CoverageMetric, CoverageTuple>} FileCoverage */
/** @typedef {{revision?: string, dirty?: boolean, generatedAt?: string, scope?: string}} CoverageProvenance */
/** @typedef {{path: string, category?: string, treatment?: string, producer?: string, verdict?: string, rationale?: string}} SourceOwnership */
/** @typedef {{path: string, evidence: string, declaredStories: number, declaredPlays: number, executedStories: number, coverage?: FileCoverage}} UiEvidence */
/** @typedef {{verdict: 'pass' | 'fail', issues: string[], categoryCounts: Record<string, number>, sources: SourceOwnership[], ui: UiEvidence[], uiTotals: FileCoverage}} SourceEvidence */
/** @typedef {{status: 'available', incompatibleFiles: Array<{path: string, reason: string}>, coverage: FileCoverage} | {status: 'withheld', incompatibleFiles: Array<{path: string, reason: string}>, coverage?: undefined}} CombinedAutomation */

/** @type {readonly CoverageMetric[]} */
export const COVERAGE_METRICS = Object.freeze([
  ...SHARED_COVERAGE_METRICS,
])

/** @param {Record<string, any>} summary @param {string} repositoryRoot @param {string[]} [includedPaths] @returns {Record<string, FileCoverage>} */
const normalizeSummaryFiles = (summary, repositoryRoot, includedPaths) => {
  const included = includedPaths ? new Set(includedPaths) : undefined
  const entries = Object.entries(summary)
    .filter(([path]) => path !== 'total')
    .map(([path, coverage]) => /** @type {[string, FileCoverage]} */ (
      [normalizeCoveragePath(path, repositoryRoot), exactCoverage(coverage)]
    ))
    .filter(([path]) => !included || included.has(path))
  entries.sort((left, right) => String(left[0]).localeCompare(String(right[0])))
  return Object.fromEntries(entries)
}

/**
 * Create a generated contract whose shape makes cross-producer comparison
 * impossible by construction.
 *
 * @param {{summaries: Record<string, Record<string, any>>, repositoryRoot: string, ownedPathsByProducer: Record<string, string[]>, registryDigest: string}} input
 */
export const createOwnerCoverageBaseline = ({
  summaries,
  repositoryRoot,
  ownedPathsByProducer,
  registryDigest,
}) => ({
  schemaVersion: 2,
  notice: 'Generated by npm run coverage:update-baseline. Do not edit manually.',
  registryDigest,
  owners: Object.fromEntries(['node', 'storybook'].map((producer) => [producer, {
    producer,
    files: normalizeSummaryFiles(
      summaries[producer],
      repositoryRoot,
      ownedPathsByProducer[producer] ?? []
    ),
  }])),
})

/**
 * @param {{baselineRegistryDigest: string, currentRegistryDigest: string, ownershipReviewed: boolean}} input
 */
export const ownershipReviewIssues = ({
  baselineRegistryDigest,
  currentRegistryDigest,
  ownershipReviewed,
}) => baselineRegistryDigest !== currentRegistryDigest && !ownershipReviewed
  ? ['Evidence ownership changed. Review the registry diff before updating the baseline with COVERAGE_EVIDENCE_REVIEW_OWNERSHIP=1']
  : []

/** @type {Readonly<FileCoverage>} */
const EMPTY_COVERAGE = Object.freeze(/** @type {FileCoverage} */ (Object.fromEntries(
  COVERAGE_METRICS.map((metric) => [metric, Object.freeze({ covered: 0, total: 0 })])
)))

/** @param {Record<string, FileCoverage>} files */
const createRollups = (files) => Object.fromEntries(
  ['shared', 'backend', 'frontend'].map((workspace) => {
    const prefix = `${workspace}/src/`
    const recursive = Object.entries(files)
      .filter(([path]) => path.startsWith(prefix))
      .map(([, coverage]) => coverage)
    const direct = Object.entries(files)
      .filter(([path]) => path.startsWith(prefix) && !path.slice(prefix.length).includes('/'))
      .map(([, coverage]) => coverage)
    return [workspace, {
      direct: /** @type {FileCoverage} */ (sumCoverage(direct)),
      recursive: /** @type {FileCoverage} */ (sumCoverage(recursive)),
    }]
  })
)

/** @param {{covered: number, total: number}} current @param {{covered: number, total: number}} baseline */
const compareMetric = (current, baseline) => {
  const currentUncovered = current.total - current.covered
  const baselineUncovered = baseline.total - baseline.covered
  const unchanged = current.covered === baseline.covered && current.total === baseline.total
  const uncoveredPreserved = currentUncovered <= baselineUncovered
  const proportionPreserved = current.total === 0
    ? true
    : baseline.total === 0
      ? current.covered === current.total
      : current.covered * baseline.total >= baseline.covered * current.total
  return {
    current,
    baseline,
    currentUncovered,
    baselineUncovered,
    status: unchanged
      ? 'unchanged'
      : uncoveredPreserved && proportionPreserved
        ? 'improvement'
        : 'regression',
  }
}

/**
 * Evaluate a parsed Vitest coverage summary against a parsed generated baseline.
 *
 * @param {{summary: Record<string, any>, baseline: {files: Record<string, FileCoverage>}, repositoryRoot: string, mode?: 'check' | 'update-baseline', provenance?: CoverageProvenance, gatedPaths?: string[], sourceEvidence?: SourceEvidence, allowFileSetChanges?: boolean}} input
 */
export const evaluateCoverage = ({
  summary,
  baseline,
  repositoryRoot,
  mode = 'check',
  provenance = {},
  gatedPaths,
  sourceEvidence,
  allowFileSetChanges = false,
}) => {
  const currentFiles = normalizeSummaryFiles(summary, repositoryRoot, gatedPaths)
  const paths = [...new Set([
    ...Object.keys(currentFiles),
    ...Object.keys(baseline.files),
  ])].sort()
  const files = paths.map((path) => {
    const hasCurrent = currentFiles[path] !== undefined
    const hasBaseline = baseline.files[path] !== undefined
    const current = currentFiles[path] ?? EMPTY_COVERAGE
    const expected = baseline.files[path] ?? EMPTY_COVERAGE
    const metrics = Object.fromEntries(COVERAGE_METRICS.map((metric) => [
      metric,
      compareMetric(current[metric], expected[metric]),
    ]))
    const statuses = Object.values(metrics).map(({ status }) => status)
    const metricOutcome = statuses.includes('regression')
      ? 'regression'
      : statuses.includes('improvement')
        ? 'improvement'
        : 'unchanged'
    const status = !hasBaseline
      ? 'new-file'
      : !hasCurrent
        ? 'deleted-file'
        : metricOutcome
    const outcome = status === 'new-file' || status === 'deleted-file'
      ? metricOutcome === 'unchanged' ? 'improvement' : metricOutcome
      : metricOutcome
    return { path, current, baseline: expected, metrics, status, outcome }
  })
  const changes = files.filter(({ status }) => status !== 'unchanged')
  const hasRegression = changes.some(({ status, outcome }) =>
    outcome === 'regression' && !(allowFileSetChanges && ['new-file', 'deleted-file'].includes(status))
  )
  const sourceEvidenceFailed = sourceEvidence?.verdict === 'fail'

  return {
    mode,
    verdict: sourceEvidenceFailed || hasRegression || (mode === 'check' && changes.length > 0) ? 'fail' : 'pass',
    changes,
    files,
    global: gatedPaths
      ? /** @type {FileCoverage} */ (sumCoverage(Object.values(currentFiles)))
      : /** @type {FileCoverage} */ (exactCoverage(summary.total)),
    rollups: createRollups(currentFiles),
    provenance,
    sourceEvidence,
  }
}

/**
 * Evaluate each exact contract only against evidence from its required
 * producer. Combined reach remains informational.
 *
 * @param {{summaries: Record<string, Record<string, any>>, baseline: {schemaVersion?: number, registryDigest?: string, owners: Record<string, {producer: string, files: Record<string, FileCoverage>}>}, repositoryRoot: string, ownedPathsByProducer: Record<string, string[]>, mode?: 'check' | 'update-baseline', allowFileSetChanges?: boolean, producerIssues?: string[], sourceEvidence?: SourceEvidence, combinedAutomation?: CombinedAutomation, provenance?: CoverageProvenance}} input
 */
export const evaluateOwnerCoverage = ({
  summaries,
  baseline,
  repositoryRoot,
  ownedPathsByProducer,
  mode = 'check',
  allowFileSetChanges = false,
  producerIssues = [],
  sourceEvidence,
  combinedAutomation,
  provenance = {},
}) => {
  const owners = Object.fromEntries(['node', 'storybook'].map((producer) => [producer,
    evaluateCoverage({
      summary: summaries[producer],
      baseline: baseline.owners[producer],
      repositoryRoot,
      mode,
      gatedPaths: ownedPathsByProducer[producer] ?? [],
      allowFileSetChanges,
    }),
  ]))
  const ownerFailed = Object.values(owners).some(({ verdict }) => verdict === 'fail')
  const sourceEvidenceFailed = sourceEvidence?.verdict === 'fail'
  return {
    mode,
    verdict: ownerFailed || sourceEvidenceFailed || producerIssues.length > 0 ? 'fail' : 'pass',
    owners,
    producerIssues,
    sourceEvidence,
    combinedOwnedRuntime: /** @type {FileCoverage} */ (createCombinedOwnedRuntimeReach({
      repositoryRoot,
      summaries,
      ownedPathsByProducer,
    })),
    combinedAutomation,
    provenance,
  }
}

/** @type {Record<CoverageMetric, string>} */
const METRIC_LABELS = Object.freeze({
  statements: 'Statements',
  branches: 'Branches',
  functions: 'Functions',
  lines: 'Lines',
})

/** @param {{covered: number, total: number}} value */
const percentage = ({ covered, total }) => total === 0 ? 100 : covered * 100 / total

/** @param {{covered: number, total: number}} value */
const formatTuple = (value) => `${value.covered}/${value.total} (${percentage(value).toFixed(2)}%)`

/** @param {unknown} value */
const escapeHtml = (value) => String(value ?? '')
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')
  .replaceAll("'", '&#39;')
  .replaceAll('`', '&#96;')

/** @param {unknown} value */
const escapeMarkdown = (value) => String(value ?? '')
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('|', '\\|')
  .replaceAll('`', '\\`')

/** @param {string} status */
const statusLabel = (status) => ({
  unchanged: 'Unchanged',
  improvement: 'Improvement - baseline update required',
  regression: 'Regression',
  'new-file': 'New gated file',
  'deleted-file': 'Deleted gated file',
})[status] ?? status

/** @param {{provenance: CoverageProvenance}} evaluation */
const sourceLines = (evaluation) => {
  const { revision = 'unknown', dirty = false, generatedAt = 'unknown', scope = 'merged unit + Storybook' } = evaluation.provenance
  return { revision, state: dirty ? 'dirty' : 'clean', generatedAt, scope }
}

/** @param {string} title @param {FileCoverage} coverage */
const markdownMetricSection = (title, coverage) => [
  `## ${title}`,
  '',
  '| Metric | Covered / total | Uncovered |',
  '| --- | ---: | ---: |',
  ...COVERAGE_METRICS.map((metric) =>
    `| ${METRIC_LABELS[metric]} | ${formatTuple(coverage[metric])} | ${coverage[metric].total - coverage[metric].covered} |`
  ),
  '',
]

/** @param {ReturnType<typeof evaluateOwnerCoverage>} evaluation */
const renderOwnerCoverageMarkdown = (evaluation) => {
  const source = sourceLines(evaluation)
  const lines = [
    '# Coverage evidence',
    '',
    `**${evaluation.verdict.toUpperCase()}** - producer-owned exact baseline verdict`,
    '',
    `- Revision: ${escapeMarkdown(source.revision)}`,
    `- Source state: ${source.state}`,
    `- Generated: ${escapeMarkdown(source.generatedAt)}`,
    '',
  ]
  const ownerSections = [
    ['node', 'Node-owned runtime reach (gating - Node Vitest)'],
    ['storybook', 'Storybook controller reach (gating - Storybook Chromium)'],
  ]
  for (const [producer, title] of ownerSections) {
    const owner = evaluation.owners[producer]
    lines.push(...markdownMetricSection(title, owner.global))
    lines.push(`Owner verdict: **${owner.verdict.toUpperCase()}**`, '')
  }

  if (evaluation.sourceEvidence) {
    lines.push(...markdownMetricSection(
      'Storybook rendered-UI reach (informational)',
      evaluation.sourceEvidence.uiTotals
    ))
  }
  lines.push(...markdownMetricSection(
    'Combined owned runtime reach (informational)',
    evaluation.combinedOwnedRuntime
  ))
  lines.push('## Combined automation reach (informational)', '')
  if (evaluation.combinedAutomation?.status === 'available') {
    lines.push(
      'Compatible Node and Storybook Istanbul maps are unioned. Playwright is not included.',
      '',
      ...markdownMetricSection('Compatible automation map union', evaluation.combinedAutomation.coverage)
    )
  } else {
    lines.push(
      'Withheld because overlapping Node and Storybook maps are not compatible. Owner verdicts remain valid.',
      '',
      ...(evaluation.combinedAutomation?.incompatibleFiles ?? []).map(({ path, reason }) =>
        `- ${escapeMarkdown(path)}: ${escapeMarkdown(reason)}`
      ),
      ''
    )
  }

  if (evaluation.sourceEvidence) {
    lines.push(
      '## Reviewed evidence registry',
      '',
      '| Source file | Treatment | Required producer | Verdict rule | Rationale |',
      '| --- | --- | --- | --- | --- |',
      ...evaluation.sourceEvidence.sources.map((sourceEntry) =>
        `| ${escapeMarkdown(sourceEntry.path)} | ${escapeMarkdown(sourceEntry.treatment ?? 'Unclassified')} | ${escapeMarkdown(sourceEntry.producer ?? 'None')} | ${escapeMarkdown(sourceEntry.verdict ?? 'None')} | ${escapeMarkdown(sourceEntry.rationale ?? 'No reviewed rationale')} |`
      ),
      '',
      '## Storybook UI evidence',
      '',
      '| UI source | Evidence | Story execution | Plays |',
      '| --- | --- | --- | ---: |',
      ...evaluation.sourceEvidence.ui.map((item) =>
        `| ${escapeMarkdown(item.path)} | ${escapeMarkdown(item.evidence)} | ${item.executedStories}/${item.declaredStories} stories executed | ${item.declaredPlays} |`
      ),
      ''
    )
  }

  lines.push('## Changes requiring action', '')
  const changes = Object.entries(evaluation.owners).flatMap(([producer, owner]) =>
    owner.changes.map((change) => `${producer}: ${change.path}: ${statusLabel(change.status)}`)
  )
  const issues = [
    ...evaluation.producerIssues,
    ...(evaluation.sourceEvidence?.issues ?? []),
    ...changes,
  ]
  lines.push(...(issues.length > 0
    ? issues.map((issue) => `- ${escapeMarkdown(issue)}`)
    : ['None. Both owner reports exactly match their committed baselines.']))
  lines.push('', '## Istanbul explorer', '')
  if (evaluation.combinedAutomation?.status === 'available') {
    lines.push('[Open the compatible Node and Storybook line explorer](index.html).', '')
  } else {
    lines.push('Withheld with the incompatible combined automation view.', '')
  }
  return lines.join('\n')
}

/** @param {ReturnType<typeof evaluateCoverage> | ReturnType<typeof evaluateOwnerCoverage>} evaluation */
export const renderCoverageMarkdown = (evaluation) => {
  if ('owners' in evaluation) return renderOwnerCoverageMarkdown(evaluation)
  const source = sourceLines(evaluation)
  const lines = [
    '# Coverage evidence',
    '',
    `**${evaluation.verdict.toUpperCase()}** - ${escapeMarkdown(source.scope)}`,
    '',
    `- Revision: ${escapeMarkdown(source.revision)}`,
    `- Source state: ${source.state}`,
    `- Generated: ${escapeMarkdown(source.generatedAt)}`,
    '',
    '## Gated logic totals',
    '',
    '| Metric | Covered / total | Uncovered |',
    '| --- | ---: | ---: |',
    ...COVERAGE_METRICS.map((metric) =>
      `| ${METRIC_LABELS[metric]} | ${formatTuple(evaluation.global[metric])} | ${evaluation.global[metric].total - evaluation.global[metric].covered} |`
    ),
    '',
    '## Gated logic recursive workspace rollups',
    '',
    '| Workspace | Metric | Covered / total | Uncovered |',
    '| --- | --- | ---: | ---: |',
    ...Object.entries(evaluation.rollups).flatMap(([workspace, { recursive }]) =>
      COVERAGE_METRICS.map((metric) =>
        `| ${workspace} (recursive) | ${METRIC_LABELS[metric]} | ${formatTuple(recursive[metric])} | ${recursive[metric].total - recursive[metric].covered} |`
      )
    ),
    '',
  ]
  const sourceEvidence = evaluation.sourceEvidence
  if (sourceEvidence) {
    lines.push(
      '## Source evidence ownership',
      '',
      '| Category | Source files |',
      '| --- | ---: |',
      ...Object.entries(sourceEvidence.categoryCounts).map(([category, count]) =>
        `| ${escapeMarkdown(category)} | ${count} |`
      ),
      '',
      '| Source file | Evidence treatment | Rationale |',
      '| --- | --- | --- |',
      ...sourceEvidence.sources.map(({ path, category, treatment, rationale }) =>
        `| ${escapeMarkdown(path)} | ${escapeMarkdown(treatment ?? category ?? 'Unclassified')} | ${escapeMarkdown(rationale ?? 'No evidence owner')} |`
      ),
      '',
      '## UI source coverage (informational)',
      '',
      'Coverage percentages expose Storybook reach but do not affect the logic baseline. Missing UI coverage, story discovery, or browser execution is still a source-evidence failure.',
      '',
      '| Metric | Covered / total | Uncovered |',
      '| --- | ---: | ---: |',
      ...COVERAGE_METRICS.map((metric) => {
        const value = sourceEvidence.uiTotals[metric]
        return `| ${METRIC_LABELS[metric]} | ${formatTuple(value)} | ${value.total - value.covered} |`
      }),
      '',
      '| UI source | Evidence | Story execution | Plays | Statements | Branches | Functions | Lines |',
      '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |',
      ...sourceEvidence.ui.map((item) =>
        `| ${escapeMarkdown(item.path)} | ${escapeMarkdown(item.evidence)} | ${item.executedStories}/${item.declaredStories} stories executed | ${item.declaredPlays} | ${item.coverage ? formatTuple(item.coverage.statements) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.branches) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.functions) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.lines) : 'Not reported'} |`
      ),
      ''
    )
  }
  lines.push('## Changes requiring action', '')
  const sourceIssues = evaluation.sourceEvidence?.issues ?? []
  if (evaluation.changes.length === 0 && sourceIssues.length === 0) {
    lines.push('None. The report exactly matches the committed baseline.')
  } else {
    lines.push('| File | Status | Outcome |', '| --- | --- | --- |')
    for (const file of evaluation.changes) {
      lines.push(`| ${escapeMarkdown(file.path)} | ${statusLabel(file.status)} | ${statusLabel(file.outcome)} |`)
    }
    for (const issue of sourceIssues) {
      lines.push(`| ${escapeMarkdown(issue)} | Source evidence | Regression |`)
    }
  }
  lines.push(
    '',
    '## Gated files',
    '',
    '| File | Metric | Current | Baseline | Current uncovered | Baseline uncovered | Status |',
    '| --- | --- | ---: | ---: | ---: | ---: | --- |'
  )
  for (const file of evaluation.files) {
    for (const metric of COVERAGE_METRICS) {
      const comparison = file.metrics[metric]
      lines.push(
        `| ${escapeMarkdown(file.path)} | ${METRIC_LABELS[metric]} | ${formatTuple(comparison.current)} | ${formatTuple(comparison.baseline)} | ${comparison.currentUncovered} | ${comparison.baselineUncovered} | ${statusLabel(comparison.status)} |`
      )
    }
  }
  lines.push(
    '',
    '## Istanbul explorer',
    '',
    '[Open the line-level Istanbul explorer](index.html). Its directory rows count direct files only; the workspace totals above are explicitly recursive.',
    ''
  )
  return lines.join('\n')
}

