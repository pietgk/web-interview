import { relative, resolve, sep } from 'node:path'

/** @typedef {'statements' | 'branches' | 'functions' | 'lines'} CoverageMetric */
/** @typedef {{covered: number, total: number}} CoverageTuple */
/** @typedef {Record<CoverageMetric, CoverageTuple>} FileCoverage */
/** @typedef {{revision?: string, dirty?: boolean, generatedAt?: string, scope?: string}} CoverageProvenance */
/** @typedef {{path: string, category?: string, rationale?: string}} SourceOwnership */
/** @typedef {{path: string, evidence: string, declaredStories: number, declaredPlays: number, executedStories: number, coverage?: FileCoverage}} UiEvidence */
/** @typedef {{verdict: 'pass' | 'fail', issues: string[], categoryCounts: Record<string, number>, sources: SourceOwnership[], ui: UiEvidence[], uiTotals: FileCoverage}} SourceEvidence */

/** @type {readonly CoverageMetric[]} */
export const COVERAGE_METRICS = Object.freeze([
  'statements',
  'branches',
  'functions',
  'lines',
])

/** @param {string} path @param {string} repositoryRoot */
const normalizePath = (path, repositoryRoot) =>
  relative(resolve(repositoryRoot), resolve(path)).split(sep).join('/')

/** @param {Record<string, any>} coverage @returns {FileCoverage} */
const exactCoverage = (coverage) => /** @type {FileCoverage} */ (Object.fromEntries(
  COVERAGE_METRICS.map((metric) => [metric, {
    covered: coverage[metric].covered,
    total: coverage[metric].total,
  }])
))

/** @param {Record<string, any>} summary @param {string} repositoryRoot @param {string[]} [includedPaths] @returns {Record<string, FileCoverage>} */
const normalizeSummaryFiles = (summary, repositoryRoot, includedPaths) => {
  const included = includedPaths ? new Set(includedPaths) : undefined
  const entries = Object.entries(summary)
    .filter(([path]) => path !== 'total')
    .map(([path, coverage]) => /** @type {[string, FileCoverage]} */ (
      [normalizePath(path, repositoryRoot), exactCoverage(coverage)]
    ))
    .filter(([path]) => !included || included.has(path))
  entries.sort((left, right) => String(left[0]).localeCompare(String(right[0])))
  return Object.fromEntries(entries)
}

/**
 * Create the generated exact per-file contract from a parsed Vitest summary.
 * @param {{summary: Record<string, any>, repositoryRoot: string, gatedPaths?: string[]}} input
 */
export const createCoverageBaseline = ({ summary, repositoryRoot, gatedPaths }) => ({
  schemaVersion: 1,
  notice: 'Generated by npm run coverage:update-baseline. Do not edit manually.',
  files: normalizeSummaryFiles(summary, repositoryRoot, gatedPaths),
})

/** @type {Readonly<FileCoverage>} */
const EMPTY_COVERAGE = Object.freeze(/** @type {FileCoverage} */ (Object.fromEntries(
  COVERAGE_METRICS.map((metric) => [metric, Object.freeze({ covered: 0, total: 0 })])
)))

/** @param {FileCoverage[]} coverages @returns {FileCoverage} */
const sumCoverage = (coverages) => /** @type {FileCoverage} */ (Object.fromEntries(COVERAGE_METRICS.map((metric) => [
  metric,
  coverages.reduce((sum, coverage) => ({
    covered: sum.covered + coverage[metric].covered,
    total: sum.total + coverage[metric].total,
  }), { covered: 0, total: 0 }),
])))

/** @param {Record<string, FileCoverage>} files */
const createRollups = (files) => Object.fromEntries(
  ['shared', 'backend', 'frontend'].map((workspace) => {
    const prefix = `${workspace}/src/`
    const recursive = Object.entries(files)
      .filter(([path]) => path.startsWith(prefix))
      .map(([, coverage]) => coverage)
    const direct = Object.entries(files)
      .filter(([path]) => path.startsWith(prefix) && !path.slice(prefix.length).includes('/'))
      .map(([, coverage]) => coverage)
    return [workspace, {
      direct: sumCoverage(direct),
      recursive: sumCoverage(recursive),
    }]
  })
)

/** @param {{covered: number, total: number}} current @param {{covered: number, total: number}} baseline */
const compareMetric = (current, baseline) => {
  const currentUncovered = current.total - current.covered
  const baselineUncovered = baseline.total - baseline.covered
  const unchanged = current.covered === baseline.covered && current.total === baseline.total
  const uncoveredPreserved = currentUncovered <= baselineUncovered
  const proportionPreserved = current.total === 0
    ? true
    : baseline.total === 0
      ? current.covered === current.total
      : current.covered * baseline.total >= baseline.covered * current.total
  return {
    current,
    baseline,
    currentUncovered,
    baselineUncovered,
    status: unchanged
      ? 'unchanged'
      : uncoveredPreserved && proportionPreserved
        ? 'improvement'
        : 'regression',
  }
}

/**
 * Evaluate a parsed Vitest coverage summary against a parsed generated baseline.
 *
 * @param {{summary: Record<string, any>, baseline: {files: Record<string, FileCoverage>}, repositoryRoot: string, mode?: 'check' | 'update-baseline', provenance?: CoverageProvenance, gatedPaths?: string[], sourceEvidence?: SourceEvidence}} input
 */
export const evaluateCoverage = ({
  summary,
  baseline,
  repositoryRoot,
  mode = 'check',
  provenance = {},
  gatedPaths,
  sourceEvidence,
}) => {
  const currentFiles = normalizeSummaryFiles(summary, repositoryRoot, gatedPaths)
  const paths = [...new Set([
    ...Object.keys(currentFiles),
    ...Object.keys(baseline.files),
  ])].sort()
  const files = paths.map((path) => {
    const hasCurrent = currentFiles[path] !== undefined
    const hasBaseline = baseline.files[path] !== undefined
    const current = currentFiles[path] ?? EMPTY_COVERAGE
    const expected = baseline.files[path] ?? EMPTY_COVERAGE
    const metrics = Object.fromEntries(COVERAGE_METRICS.map((metric) => [
      metric,
      compareMetric(current[metric], expected[metric]),
    ]))
    const statuses = Object.values(metrics).map(({ status }) => status)
    const metricOutcome = statuses.includes('regression')
      ? 'regression'
      : statuses.includes('improvement')
        ? 'improvement'
        : 'unchanged'
    const status = !hasBaseline
      ? 'new-file'
      : !hasCurrent
        ? 'deleted-file'
        : metricOutcome
    const outcome = status === 'new-file' || status === 'deleted-file'
      ? metricOutcome === 'unchanged' ? 'improvement' : metricOutcome
      : metricOutcome
    return { path, current, baseline: expected, metrics, status, outcome }
  })
  const changes = files.filter(({ status }) => status !== 'unchanged')
  const hasRegression = changes.some(({ outcome }) => outcome === 'regression')
  const sourceEvidenceFailed = sourceEvidence?.verdict === 'fail'

  return {
    mode,
    verdict: sourceEvidenceFailed || hasRegression || (mode === 'check' && changes.length > 0) ? 'fail' : 'pass',
    changes,
    files,
    global: gatedPaths ? sumCoverage(Object.values(currentFiles)) : exactCoverage(summary.total),
    rollups: createRollups(currentFiles),
    provenance,
    sourceEvidence,
  }
}

/** @type {Record<CoverageMetric, string>} */
const METRIC_LABELS = Object.freeze({
  statements: 'Statements',
  branches: 'Branches',
  functions: 'Functions',
  lines: 'Lines',
})

/** @param {{covered: number, total: number}} value */
const percentage = ({ covered, total }) => total === 0 ? 100 : covered * 100 / total

/** @param {{covered: number, total: number}} value */
const formatTuple = (value) => `${value.covered}/${value.total} (${percentage(value).toFixed(2)}%)`

/** @param {unknown} value */
const escapeHtml = (value) => String(value ?? '')
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')
  .replaceAll("'", '&#39;')
  .replaceAll('`', '&#96;')

/** @param {unknown} value */
const escapeMarkdown = (value) => String(value ?? '')
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('|', '\\|')
  .replaceAll('`', '\\`')

/** @param {string} status */
const statusLabel = (status) => ({
  unchanged: 'Unchanged',
  improvement: 'Improvement - baseline update required',
  regression: 'Regression',
  'new-file': 'New gated file',
  'deleted-file': 'Deleted gated file',
})[status] ?? status

/** @param {ReturnType<typeof evaluateCoverage>} evaluation */
const sourceLines = (evaluation) => {
  const { revision = 'unknown', dirty = false, generatedAt = 'unknown', scope = 'merged unit + Storybook' } = evaluation.provenance
  return { revision, state: dirty ? 'dirty' : 'clean', generatedAt, scope }
}

/** @param {ReturnType<typeof evaluateCoverage>} evaluation */
export const renderCoverageMarkdown = (evaluation) => {
  const source = sourceLines(evaluation)
  const lines = [
    '# Coverage evidence',
    '',
    `**${evaluation.verdict.toUpperCase()}** - ${escapeMarkdown(source.scope)}`,
    '',
    `- Revision: ${escapeMarkdown(source.revision)}`,
    `- Source state: ${source.state}`,
    `- Generated: ${escapeMarkdown(source.generatedAt)}`,
    '',
    '## Gated logic totals',
    '',
    '| Metric | Covered / total | Uncovered |',
    '| --- | ---: | ---: |',
    ...COVERAGE_METRICS.map((metric) =>
      `| ${METRIC_LABELS[metric]} | ${formatTuple(evaluation.global[metric])} | ${evaluation.global[metric].total - evaluation.global[metric].covered} |`
    ),
    '',
    '## Gated logic recursive workspace rollups',
    '',
    '| Workspace | Metric | Covered / total | Uncovered |',
    '| --- | --- | ---: | ---: |',
    ...Object.entries(evaluation.rollups).flatMap(([workspace, { recursive }]) =>
      COVERAGE_METRICS.map((metric) =>
        `| ${workspace} (recursive) | ${METRIC_LABELS[metric]} | ${formatTuple(recursive[metric])} | ${recursive[metric].total - recursive[metric].covered} |`
      )
    ),
    '',
  ]
  const sourceEvidence = evaluation.sourceEvidence
  if (sourceEvidence) {
    lines.push(
      '## Source evidence ownership',
      '',
      '| Category | Source files |',
      '| --- | ---: |',
      ...Object.entries(sourceEvidence.categoryCounts).map(([category, count]) =>
        `| ${escapeMarkdown(category)} | ${count} |`
      ),
      '',
      '| Source file | Evidence category | Rationale |',
      '| --- | --- | --- |',
      ...sourceEvidence.sources.map(({ path, category, rationale }) =>
        `| ${escapeMarkdown(path)} | ${escapeMarkdown(category ?? 'Unclassified')} | ${escapeMarkdown(rationale ?? 'No evidence owner')} |`
      ),
      '',
      '## UI source coverage (informational)',
      '',
      'Coverage percentages expose Storybook reach but do not affect the logic baseline. Missing UI coverage, story discovery, or browser execution is still a source-evidence failure.',
      '',
      '| Metric | Covered / total | Uncovered |',
      '| --- | ---: | ---: |',
      ...COVERAGE_METRICS.map((metric) => {
        const value = sourceEvidence.uiTotals[metric]
        return `| ${METRIC_LABELS[metric]} | ${formatTuple(value)} | ${value.total - value.covered} |`
      }),
      '',
      '| UI source | Evidence | Story execution | Plays | Statements | Branches | Functions | Lines |',
      '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |',
      ...sourceEvidence.ui.map((item) =>
        `| ${escapeMarkdown(item.path)} | ${escapeMarkdown(item.evidence)} | ${item.executedStories}/${item.declaredStories} stories executed | ${item.declaredPlays} | ${item.coverage ? formatTuple(item.coverage.statements) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.branches) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.functions) : 'Not reported'} | ${item.coverage ? formatTuple(item.coverage.lines) : 'Not reported'} |`
      ),
      ''
    )
  }
  lines.push('## Changes requiring action', '')
  const sourceIssues = evaluation.sourceEvidence?.issues ?? []
  if (evaluation.changes.length === 0 && sourceIssues.length === 0) {
    lines.push('None. The report exactly matches the committed baseline.')
  } else {
    lines.push('| File | Status | Outcome |', '| --- | --- | --- |')
    for (const file of evaluation.changes) {
      lines.push(`| ${escapeMarkdown(file.path)} | ${statusLabel(file.status)} | ${statusLabel(file.outcome)} |`)
    }
    for (const issue of sourceIssues) {
      lines.push(`| ${escapeMarkdown(issue)} | Source evidence | Regression |`)
    }
  }
  lines.push(
    '',
    '## Gated files',
    '',
    '| File | Metric | Current | Baseline | Current uncovered | Baseline uncovered | Status |',
    '| --- | --- | ---: | ---: | ---: | ---: | --- |'
  )
  for (const file of evaluation.files) {
    for (const metric of COVERAGE_METRICS) {
      const comparison = file.metrics[metric]
      lines.push(
        `| ${escapeMarkdown(file.path)} | ${METRIC_LABELS[metric]} | ${formatTuple(comparison.current)} | ${formatTuple(comparison.baseline)} | ${comparison.currentUncovered} | ${comparison.baselineUncovered} | ${statusLabel(comparison.status)} |`
      )
    }
  }
  lines.push(
    '',
    '## Istanbul explorer',
    '',
    '[Open the line-level Istanbul explorer](index.html). Its directory rows count direct files only; the workspace totals above are explicitly recursive.',
    ''
  )
  return lines.join('\n')
}

