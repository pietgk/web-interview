import assert from 'node:assert/strict'
import { test } from 'vitest'
import {
  createCoverageBaseline,
  evaluateCoverage,
  renderCoverageHtml,
  renderCoverageMarkdown,
} from './coverage-evidence.mjs'

const REPOSITORY_ROOT = '/repo'
const METRICS = ['statements', 'branches', 'functions', 'lines']

/** @param {number} covered @param {number} total */
const tuple = (covered, total) => ({ covered, total })

/** @param {Partial<Record<'statements' | 'branches' | 'functions' | 'lines', {covered: number, total: number}>>} [coverage] */
const fileCoverage = ({
  statements = tuple(4, 5),
  branches = tuple(2, 3),
  functions = tuple(1, 1),
  lines = tuple(4, 5),
} = {}) => ({ statements, branches, functions, lines })

/** @param {Record<string, ReturnType<typeof fileCoverage>>} files */
const summary = (files) => ({
  total: fileCoverage(),
  ...Object.fromEntries(
    Object.entries(files).map(([path, coverage]) => [
      `${REPOSITORY_ROOT}/${path}`,
      coverage,
    ])
  ),
})

/** @param {Record<string, ReturnType<typeof fileCoverage>>} files */
const baseline = (files) => ({
  schemaVersion: 1,
  notice: 'Generated by npm run coverage:ratchet. Do not edit manually.',
  files,
})

test('accepts an exact per-file baseline match', () => {
  const files = { 'shared/src/example.js': fileCoverage() }
  const evaluation = evaluateCoverage({
    summary: summary(files),
    baseline: baseline(files),
    repositoryRoot: REPOSITORY_ROOT,
  })

  assert.equal(evaluation.verdict, 'pass')
  assert.deepEqual(evaluation.changes, [])
  assert.deepEqual(evaluation.files.map(({ path, status }) => ({ path, status })), [
    { path: 'shared/src/example.js', status: 'unchanged' },
  ])
  assert.deepEqual(Object.keys(evaluation.files[0].current), METRICS)
})

test('keeps informational UI coverage outside the exact logic ratchet', () => {
  const logicPath = 'shared/src/example.js'
  const uiPath = 'frontend/src/App.jsx'
  const logicCoverage = fileCoverage()
  const evaluation = evaluateCoverage({
    summary: summary({
      [logicPath]: logicCoverage,
      [uiPath]: fileCoverage({ statements: tuple(1, 5) }),
    }),
    baseline: baseline({ [logicPath]: logicCoverage }),
    repositoryRoot: REPOSITORY_ROOT,
    gatedPaths: [logicPath],
  })

  assert.equal(evaluation.verdict, 'pass')
  assert.deepEqual(evaluation.files.map(({ path }) => path), [logicPath])
  assert.deepEqual(evaluation.global.statements, logicCoverage.statements)
})

test('rejects an added uncovered item in both check and ratchet modes', () => {
  const path = 'backend/src/example.js'
  const expected = fileCoverage()
  const current = fileCoverage({ statements: tuple(4, 6) })

  /** @type {Array<'check' | 'ratchet'>} */
  const modes = ['check', 'ratchet']
  for (const mode of modes) {
    const evaluation = evaluateCoverage({
      summary: summary({ [path]: current }),
      baseline: baseline({ [path]: expected }),
      repositoryRoot: REPOSITORY_ROOT,
      mode,
    })

    assert.equal(evaluation.verdict, 'fail')
    assert.equal(evaluation.files[0].status, 'regression')
    assert.equal(evaluation.files[0].metrics.statements.status, 'regression')
    assert.equal(evaluation.files[0].metrics.statements.currentUncovered, 2)
    assert.equal(evaluation.files[0].metrics.statements.baselineUncovered, 1)
  }
})

test('rejects removal of covered code while misses remain', () => {
  const path = 'shared/src/example.js'
  const evaluation = evaluateCoverage({
    summary: summary({ [path]: fileCoverage({ statements: tuple(3, 4) }) }),
    baseline: baseline({ [path]: fileCoverage({ statements: tuple(4, 5) }) }),
    repositoryRoot: REPOSITORY_ROOT,
    mode: 'ratchet',
  })

  assert.equal(evaluation.verdict, 'fail')
  assert.equal(evaluation.files[0].metrics.statements.status, 'regression')
})

test('accepts removal of uncovered code only in ratchet mode', () => {
  const path = 'shared/src/example.js'
  const input = {
    summary: summary({ [path]: fileCoverage({ statements: tuple(4, 4) }) }),
    baseline: baseline({ [path]: fileCoverage({ statements: tuple(4, 5) }) }),
    repositoryRoot: REPOSITORY_ROOT,
  }

  assert.equal(evaluateCoverage(input).verdict, 'fail')
  assert.equal(evaluateCoverage({ ...input, mode: 'ratchet' }).verdict, 'pass')
  assert.equal(
    evaluateCoverage({ ...input, mode: 'ratchet' }).files[0].metrics.statements.status,
    'improvement'
  )
})

test('accepts fully covered code additions only in ratchet mode', () => {
  const path = 'frontend/src/todos/example.js'
  const input = {
    summary: summary({ [path]: fileCoverage({ statements: tuple(6, 6) }) }),
    baseline: baseline({ [path]: fileCoverage({ statements: tuple(4, 4) }) }),
    repositoryRoot: REPOSITORY_ROOT,
  }

  assert.equal(evaluateCoverage(input).verdict, 'fail')
  assert.equal(evaluateCoverage({ ...input, mode: 'ratchet' }).verdict, 'pass')
})

test('rejects one improved metric alongside one regressed metric', () => {
  const path = 'backend/src/example.js'
  const evaluation = evaluateCoverage({
    summary: summary({
      [path]: fileCoverage({
        statements: tuple(4, 4),
        branches: tuple(2, 4),
      }),
    }),
    baseline: baseline({ [path]: fileCoverage() }),
    repositoryRoot: REPOSITORY_ROOT,
    mode: 'ratchet',
  })

  assert.equal(evaluation.verdict, 'fail')
  assert.equal(evaluation.files[0].metrics.statements.status, 'improvement')
  assert.equal(evaluation.files[0].metrics.branches.status, 'regression')
})

test('treats zero-total metrics as one hundred percent', () => {
  const path = 'shared/src/constants.js'
  const zeroFunctions = fileCoverage({ functions: tuple(0, 0) })
  const exact = evaluateCoverage({
    summary: summary({ [path]: zeroFunctions }),
    baseline: baseline({ [path]: zeroFunctions }),
    repositoryRoot: REPOSITORY_ROOT,
  })
  const newlyUncovered = evaluateCoverage({
    summary: summary({ [path]: fileCoverage({ functions: tuple(0, 1) }) }),
    baseline: baseline({ [path]: zeroFunctions }),
    repositoryRoot: REPOSITORY_ROOT,
    mode: 'ratchet',
  })

  assert.equal(exact.verdict, 'pass')
  assert.equal(newlyUncovered.files[0].metrics.functions.status, 'regression')
})

test('reports new and deleted gated files as file-set changes', () => {
  const keptPath = 'backend/src/kept.js'
  const newPath = 'frontend/src/todos/new.js'
  const deletedPath = 'shared/src/deleted.js'
  const fullyCovered = fileCoverage({
    statements: tuple(5, 5),
    branches: tuple(2, 2),
    functions: tuple(1, 1),
    lines: tuple(5, 5),
  })
  const input = {
    summary: summary({ [keptPath]: fullyCovered, [newPath]: fullyCovered }),
    baseline: baseline({ [keptPath]: fullyCovered, [deletedPath]: fullyCovered }),
    repositoryRoot: REPOSITORY_ROOT,
  }

  const check = evaluateCoverage(input)
  assert.equal(check.verdict, 'fail')
  assert.deepEqual(check.changes.map(({ path, status }) => ({ path, status })), [
    { path: newPath, status: 'new-file' },
    { path: deletedPath, status: 'deleted-file' },
  ])
  assert.equal(evaluateCoverage({ ...input, mode: 'ratchet' }).verdict, 'pass')
})

