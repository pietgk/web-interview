test('rejects one improved metric alongside one regressed metric', () => {
  const path = 'backend/src/example.js'
  const evaluation = evaluateCoverage({
    summary: summary({
      [path]: fileCoverage({
        statements: tuple(4, 4),
        branches: tuple(2, 4),
      }),
    }),
    baseline: baseline({ [path]: fileCoverage() }),
    repositoryRoot: REPOSITORY_ROOT,
    mode: 'update-baseline',
  })

  assert.equal(evaluation.verdict, 'fail')
  assert.equal(evaluation.files[0].metrics.statements.status, 'improvement')
  assert.equal(evaluation.files[0].metrics.branches.status, 'regression')
})

test('treats zero-total metrics as one hundred percent', () => {
  const path = 'shared/src/constants.js'
  const zeroFunctions = fileCoverage({ functions: tuple(0, 0) })
  const exact = evaluateCoverage({
    summary: summary({ [path]: zeroFunctions }),
    baseline: baseline({ [path]: zeroFunctions }),
    repositoryRoot: REPOSITORY_ROOT,
  })
  const newlyUncovered = evaluateCoverage({
    summary: summary({ [path]: fileCoverage({ functions: tuple(0, 1) }) }),
    baseline: baseline({ [path]: zeroFunctions }),
    repositoryRoot: REPOSITORY_ROOT,
    mode: 'update-baseline',
  })

  assert.equal(exact.verdict, 'pass')
  assert.equal(newlyUncovered.files[0].metrics.functions.status, 'regression')
})

test('reports new and deleted gated files as file-set changes', () => {
  const keptPath = 'backend/src/kept.js'
  const newPath = 'frontend/src/todos/new.js'
  const deletedPath = 'shared/src/deleted.js'
  const fullyCovered = fileCoverage({
    statements: tuple(5, 5),
    branches: tuple(2, 2),
    functions: tuple(1, 1),
    lines: tuple(5, 5),
  })
  const input = {
    summary: summary({ [keptPath]: fullyCovered, [newPath]: fullyCovered }),
    baseline: baseline({ [keptPath]: fullyCovered, [deletedPath]: fullyCovered }),
    repositoryRoot: REPOSITORY_ROOT,
  }

  const check = evaluateCoverage(input)
  assert.equal(check.verdict, 'fail')
  assert.deepEqual(check.changes.map(({ path, status }) => ({ path, status })), [
    { path: newPath, status: 'new-file' },
    { path: deletedPath, status: 'deleted-file' },
  ])
  assert.equal(evaluateCoverage({ ...input, mode: 'update-baseline' }).verdict, 'pass')
})

