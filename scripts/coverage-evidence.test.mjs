test('normalizes and orders paths while distinguishing direct and recursive rollups', () => {
  const backendDirect = fileCoverage({ statements: tuple(3, 5) })
  const backendNested = fileCoverage({ statements: tuple(7, 8) })
  const sharedNested = fileCoverage({ statements: tuple(2, 2) })
  const files = {
    'shared/src/z.js': sharedNested,
    'backend/src/todos/b.js': backendNested,
    'backend/src/a.js': backendDirect,
  }
  const currentSummary = summary(files)
  currentSummary.total = fileCoverage({ statements: tuple(12, 15) })

  const evaluation = evaluateCoverage({
    summary: currentSummary,
    baseline: baseline(files),
    repositoryRoot: `${REPOSITORY_ROOT}/nested/..`,
  })

  assert.deepEqual(evaluation.files.map(({ path }) => path), [
    'backend/src/a.js',
    'backend/src/todos/b.js',
    'shared/src/z.js',
  ])
  assert.deepEqual(evaluation.global.statements, tuple(12, 15))
  assert.deepEqual(evaluation.rollups.backend.direct.statements, tuple(3, 5))
  assert.deepEqual(evaluation.rollups.backend.recursive.statements, tuple(10, 13))
  assert.deepEqual(evaluation.rollups.shared.recursive.statements, tuple(2, 2))
  assert.deepEqual(evaluation.rollups.frontend.recursive.statements, tuple(0, 0))
})

test('renders escaped Markdown and HTML in the canonical evidence order', () => {
  const hostilePath = 'shared/src/a&<b>|.js'
  const files = { [hostilePath]: fileCoverage({ functions: tuple(0, 0) }) }
  const evaluation = evaluateCoverage({
    summary: summary(files),
    baseline: baseline(files),
    repositoryRoot: REPOSITORY_ROOT,
    provenance: {
      revision: 'abc<&>|`',
      dirty: true,
      generatedAt: '2026-08-08T12:34:56.000Z',
      scope: 'merged unit + Storybook',
    },
    sourceEvidence: {
      verdict: 'pass',
      issues: [],
      categoryCounts: {
        'logic-ratchet': 1,
        'storybook-ui': 1,
        'e2e-bootstrap': 1,
        'test-support': 0,
        'type-only': 1,
      },
      sources: [
        { path: hostilePath, category: 'logic-ratchet', rationale: 'exact coverage' },
        { path: 'frontend/src/App.jsx', category: 'storybook-ui', rationale: 'browser stories' },
      ],
      ui: [{
        path: 'frontend/src/App.jsx',
        evidence: 'frontend/src/App.stories.jsx',
        declaredStories: 2,
        declaredPlays: 2,
        executedStories: 2,
        coverage: fileCoverage({ branches: tuple(2, 3) }),
      }],
      uiTotals: fileCoverage({ branches: tuple(2, 3) }),
    },
  })

  const markdown = renderCoverageMarkdown(evaluation)
  assert.match(markdown, /abc&lt;&amp;&gt;\\\|\\`/)
  assert.match(markdown, /shared\/src\/a&amp;&lt;b&gt;\\\|\.js/)
  assert.match(markdown, /0\/0 \(100\.00%\)/)
  assert.match(markdown, /UI source coverage \(informational\)/)
  assert.match(markdown, /frontend\/src\/App\.jsx/)
  assert.match(markdown, /2\/2 stories executed/)

  const html = renderCoverageHtml(evaluation)
  assert.doesNotMatch(html, /abc<&>/)
  assert.doesNotMatch(html, /a&<b>/)
  assert.match(html, /abc&lt;&amp;&gt;\|&#96;/)
  assert.match(html, /shared\/src\/a&amp;&lt;b&gt;\|\.js/)
  assert.match(html, /href="index\.html"/)
  assert.match(html, /UI source coverage \(informational\)/)
  assert.match(html, /Source evidence ownership/)
  assert.match(html, /frontend\/src\/App\.stories\.jsx/)
  assert.match(html, /class="ui-table"/)

  const orderedHeadings = [
    'Coverage evidence',
    'Gated logic totals',
    'Gated logic recursive workspace rollups',
    'Source evidence ownership',
    'UI source coverage (informational)',
    'Changes requiring action',
    'Gated files',
    'Istanbul explorer',
  ]
  let previous = -1
  for (const heading of orderedHeadings) {
    const position = html.indexOf(heading)
    assert.ok(position > previous, `${heading} should follow the previous section`)
    previous = position
  }
})

test('creates a deterministic exact baseline without source revision state', () => {
  const generated = createCoverageBaseline({
    summary: summary({
      'shared/src/z.js': fileCoverage(),
      'backend/src/a.js': fileCoverage({ functions: tuple(0, 0) }),
    }),
    repositoryRoot: REPOSITORY_ROOT,
  })

  assert.equal(generated.schemaVersion, 1)
  assert.match(generated.notice, /Generated.*coverage:ratchet.*Do not edit/)
  assert.deepEqual(Object.keys(generated.files), [
    'backend/src/a.js',
    'shared/src/z.js',
  ])
  assert.deepEqual(generated.files['backend/src/a.js'].functions, tuple(0, 0))
  assert.equal('revision' in generated, false)
})
