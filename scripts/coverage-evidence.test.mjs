import assert from 'node:assert/strict'
import { test } from 'vitest'
import {
  createOwnerCoverageBaseline,
  evaluateCoverage,
  evaluateOwnerCoverage,
  ownershipReviewIssues,
  renderCoverageHtml,
  renderCoverageMarkdown,
} from './coverage-evidence.mjs'

const REPOSITORY_ROOT = '/repo'
const METRICS = ['statements', 'branches', 'functions', 'lines']

/** @param {number} covered @param {number} total */
const tuple = (covered, total) => ({ covered, total })

/** @param {Partial<Record<'statements' | 'branches' | 'functions' | 'lines', {covered: number, total: number}>>} [coverage] */
const fileCoverage = ({
  statements = tuple(4, 5),
  branches = tuple(2, 3),
  functions = tuple(1, 1),
  lines = tuple(4, 5),
} = {}) => ({ statements, branches, functions, lines })

/** @param {Record<string, ReturnType<typeof fileCoverage>>} files */
const summary = (files) => ({
  total: fileCoverage(),
  ...Object.fromEntries(
    Object.entries(files).map(([path, coverage]) => [
      `${REPOSITORY_ROOT}/${path}`,
      coverage,
    ])
  ),
})

/** @param {Record<string, ReturnType<typeof fileCoverage>>} files */
const baseline = (files) => ({
  schemaVersion: 1,
  notice: 'Generated by npm run coverage:update-baseline. Do not edit manually.',
  files,
})

test('accepts an exact per-file baseline match', () => {
  const files = { 'shared/src/example.js': fileCoverage() }
  const evaluation = evaluateCoverage({
    summary: summary(files),
    baseline: baseline(files),
    repositoryRoot: REPOSITORY_ROOT,
  })

  assert.equal(evaluation.verdict, 'pass')
  assert.deepEqual(evaluation.changes, [])
  assert.deepEqual(evaluation.files.map(({ path, status }) => ({ path, status })), [
    { path: 'shared/src/example.js', status: 'unchanged' },
  ])
  assert.deepEqual(Object.keys(evaluation.files[0].current), METRICS)
})

test('keeps informational UI coverage outside the exact logic baseline', () => {
  const logicPath = 'shared/src/example.js'
  const uiPath = 'frontend/src/App.jsx'
  const logicCoverage = fileCoverage()
  const evaluation = evaluateCoverage({
    summary: summary({
      [logicPath]: logicCoverage,
      [uiPath]: fileCoverage({ statements: tuple(1, 5) }),
    }),
    baseline: baseline({ [logicPath]: logicCoverage }),
    repositoryRoot: REPOSITORY_ROOT,
    gatedPaths: [logicPath],
  })

  assert.equal(evaluation.verdict, 'pass')
  assert.deepEqual(evaluation.files.map(({ path }) => path), [logicPath])
  assert.deepEqual(evaluation.global.statements, logicCoverage.statements)
})

test('rejects an added uncovered item in both check and baseline update modes', () => {
  const path = 'backend/src/example.js'
  const expected = fileCoverage()
  const current = fileCoverage({ statements: tuple(4, 6) })

  /** @type {Array<'check' | 'update-baseline'>} */
  const modes = ['check', 'update-baseline']
  for (const mode of modes) {
    const evaluation = evaluateCoverage({
      summary: summary({ [path]: current }),
      baseline: baseline({ [path]: expected }),
      repositoryRoot: REPOSITORY_ROOT,
      mode,
    })

    assert.equal(evaluation.verdict, 'fail')
    assert.equal(evaluation.files[0].status, 'regression')
    assert.equal(evaluation.files[0].metrics.statements.status, 'regression')
    assert.equal(evaluation.files[0].metrics.statements.currentUncovered, 2)
    assert.equal(evaluation.files[0].metrics.statements.baselineUncovered, 1)
  }
})

